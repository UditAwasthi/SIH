export function buildJobSeed() {
  const jobs = [];
  for (let i = 0; i < 40; i += 1) {
    const template = jobTemplates[i % jobTemplates.length];
    const location = locations[i % locations.length];
    jobs.push({
      title: `${template.title}${i >= jobTemplates.length ? ` (${location})` : ""}`,
      employer: template.employer,
      location,
      sector: template.sector || sectors[i % sectors.length],
      qualification: template.qualification,
      minExperience: template.minExperience,
      salaryMin: template.salaryMin,
      salaryMax: template.salaryMax,
      requiredSkills: template.skills,
      deadline: new Date(Date.now() + (20 + (i % 40)) * 24 * 60 * 60 * 1000),
      sourceUrl: "https://www.pgrkam.com/",
      isActive: true,
    });
  }
  return jobs;
}
